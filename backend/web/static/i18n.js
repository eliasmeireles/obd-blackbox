export function readPreference(key, allowed, fallback) {
  try { const value = localStorage.getItem(key); return allowed.includes(value) ? value : fallback; } catch { return fallback; }
}
export function savePreference(key, value) {
  try { localStorage.setItem(key, value); } catch { /* Preferences remain usable for this page. */ }
}
function automaticLanguage() {
  return (navigator.languages || [navigator.language]).some(value => /^pt/i.test(value)) ? 'pt-BR' : 'en';
}
let language = readPreference('obd-language', ['auto', 'pt-BR', 'en'], 'auto');
let chosen = language === 'auto' ? automaticLanguage() : language;
export const locale = () => chosen;
export function setLanguage(value) { language = value; chosen = value === 'auto' ? automaticLanguage() : value; }
export const hasTranslation = key => Object.hasOwn(dictionaries.en, key);
const interpolation = /\{(\w+)\}/g;
export function t(key, values = {}) {
  const text = hasTranslation(key) ? dictionaries[chosen][key] : String(key);
  return text.replace(interpolation, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
export function translatePage() {
  document.documentElement.lang = chosen;
  document.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
  for (const attribute of ['aria-label', 'placeholder']) {
    document.querySelectorAll('[data-i18n-' + attribute + ']').forEach(element => {
      element.setAttribute(attribute, t(element.getAttribute('data-i18n-' + attribute)));
    });
  }
}
